const assert = require('node:assert/strict');
const routes = require('./nomad-routes.js');
routes.initialize('sc_slow={modifier={ship_speed_reduction=0.8}}', []);
const system = (id, links, ownerId = '') => ({id, name: id, links, ownerId});
const systems = [system('0', ['1', '3']), system('1', ['2'], 'closed'), system('2', []), system('3', ['4']), system('4', ['5']), system('5', [])];
const enclave = (id, type, systemId) => ({isEnclaveBranch: true, country: {id, name: id, category: 'enclave', governmentId: type}, fleet: {id}, system: systems.find(system => system.id === systemId)});
const model = {systems, countries: [{id: 'player', isNomadic: false}], capitalStarts: {player: {systemId: '0', name: 'Capital'}}, nomadStarts: {player: {systemId: '0', name: 'Ark'}}, neutral: [enclave('a', 'gov_curator_enclave', '2'), enclave('b', 'gov_curator_enclave', '5'), enclave('c', 'gov_shroudwalker_enclave', '0')], relations: {player: {closed: {closedBorders: true}}}};
let found = routes.findEnclaves(model, 'player', {avoidThreats: false});
assert.equal(found.length, 2);
model.neutral.push({...enclave('mobile', 'gov_mercenary_enclave', '0'), isEnclaveBranch: false});
assert.equal(routes.findEnclaves(model, 'player').length, 2);
assert.deepEqual(found.find(result => result.type === 'gov_curator_enclave').path, ['0', '3', '4', '5']);
assert.equal(found.find(result => result.type === 'gov_shroudwalker_enclave').cost, 0);
model.presence = [{country: {id: 'fauna'}, fleet: {id: 'cloud'}, system: systems[1]}];
model.relations.fauna = {factionHostile: true};
assert.deepEqual(routes.findEnclaves(model, 'player', {avoidThreats: false}).find(result => result.type === 'gov_curator_enclave').path, ['0', '3', '4', '5']);
model.presence = [];
model.countries[0].isNomadic = true;
found = routes.findEnclaves(model, 'player');
assert.deepEqual(found.find(result => result.type === 'gov_curator_enclave').path, ['0', '1', '2']);
model.relations = {closed: {factionHostile: true}};
assert.equal(routes.findEnclaves(model, 'player').find(result => result.type === 'gov_curator_enclave').system.id, '5');
assert.equal(routes.findEnclaves(model, 'player', {avoidThreats: false}).find(result => result.type === 'gov_curator_enclave').system.id, '2');
model.relations = {};
systems[1].starClass = 'sc_slow';
assert.equal(routes.findEnclaves(model, 'player').find(result => result.type === 'gov_curator_enclave').system.id, '5');
model.neutral.push(enclave('isolated', 'gov_artist_enclave', 'isolated'));
model.neutral.at(-1).system = system('isolated', []);
systems.push(model.neutral.at(-1).system);
assert.equal(routes.findEnclaves(model, 'player').find(result => result.type === 'gov_artist_enclave').reachable, false);
assert.throws(() => routes.findEnclaves({...model, nomadStarts: {}}, 'player'), /Capital/);
console.log('PASS: enclave types, nearest branch, capital and arkship, closed borders, threats, speed penalties, unreachable branches');
