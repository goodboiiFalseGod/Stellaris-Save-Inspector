const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
global.SaveFormat = require('./save-format.js');
const finder = require('./system-finder.js');
const {root} = require('./test-game-root.cjs');
const texts = ['deposits', 'planet_classes'].flatMap(folder => fs.readdirSync(path.join(root, 'common', folder)).filter(file => file.endsWith('.txt') && !file.includes('README')).map(file => ({path: 'common/' + folder + '/' + file, text: fs.readFileSync(path.join(root, 'common', folder, file), 'utf8')})));
finder.initialize(texts, fs.readFileSync(path.join(root, 'common/scripted_variables/07_scripted_variables_machine_age.txt'), 'utf8'));
const body = (planetClass, deposits = [], flags = []) => ({planetClass, deposits, flags});
const arc = {id: '1', name: 'Forge', ownerId: 'a', bodies: [body('pc_molten'), body('pc_barren', ['d_minerals_3']), body('pc_gas_giant'), body('pc_barren', ['d_physics_3']), body('pc_continental'), body('pc_g_star'), body('pc_astral_scar')]};
let result = finder.rank({systems: [arc]}, 'arc')[0];
assert.equal(result.count, 3);
assert.equal(result.produced.minerals, 18);
assert.equal(result.produced.alloys, 12);
assert.equal(result.gain.minerals, 15);
assert.equal(result.upkeep.energy, 100);
const tradeArc = {...arc, bodies: [...arc.bodies, body('pc_barren', ['d_trade_value_3'])]};
const tradeResult = finder.rank({systems: [tradeArc]}, 'arc')[0];
assert.equal(tradeResult.produced.trade, undefined);
assert.equal(tradeResult.gain.trade, -3);
const richArc = {id: '3', name: 'Rich', bodies: [body('pc_molten'), body('pc_barren', Array(10).fill('d_minerals_6'))]};
assert.equal(finder.rank({systems: [arc, richArc]}, 'arc', {mode: 'minerals'})[0].system.id, '3');
result = finder.rank({systems: [arc]}, 'arc', {mode: 'alloys'})[0];
assert.equal(result.produced.alloys, 18);
assert.equal(result.upkeep.energy, 125);
assert.equal(finder.rank({systems: [arc]}, 'arc', {countryId: 'b'}).length, 0);
assert.equal(finder.rank({systems: [{...arc, megastructures: ['orbital_arc_furnace_1']}]}, 'arc').length, 0);
const dyson = {id: '2', name: 'Solar', starClass: 'sc_g', bodies: [body('pc_g_star', ['d_energy_6'])]};
result = finder.rank({systems: [dyson]}, 'dyson')[0];
assert.equal(result.produced.energy, 186);
assert.equal(result.gain.energy, 180);
assert.equal(result.upkeep.alloys, 20);
for (const candidate of [{...dyson, starClass: 'sc_binary_1'}, {...dyson, bodies: [...dyson.bodies, body('pc_k_star')]}, {...dyson, bodies: [body('pc_g_star', ['d_energy_6'], ['red_giant_unstable'])]}, {...dyson, megastructures: ['dyson_swarm_1']}, {...dyson, bodies: [body('pc_g_star', ['d_energy_6'], ['has_megastructure'])]}]) assert.equal(finder.rank({systems: [candidate]}, 'dyson').length, 0);
const research = {...dyson, bodies: [body('pc_g_star', ['d_physics_3'])]};
assert.equal(finder.rank({systems: [research]}, 'dyson', {resource: 'physics_research'})[0].produced.physics_research, 93);
console.log('PASS: local Finder definitions, Arc modes, research and colonizable exclusions, Dyson output, owner filter, invalid targets');
