const assert = require('node:assert/strict');
const {model} = require('./live-map.js');
const snapshot = {schemaVersion: 1, systems: [{id: 0, nameKey: 'Sol', x: 1, y: 2, lanes: [{to: 1}]}, {id: 1, nameKey: 'Lisswyn', x: 3, y: 4, lanes: [{to: 0}]}]};
snapshot.discoveryComplete = true;
assert.throws(() => model({...snapshot, discoveryComplete: false}), /не завершён/);
assert.equal(model(snapshot).systems[0].links[0], '1');
assert.equal(model(snapshot).systems[0].live, true);
assert.equal(model({...snapshot, systems: snapshot.systems.map(system => ({...system, starClass: 'sc_black_hole'}))}).systems[0].starClass, 'sc_black_hole');
assert.throws(() => model({...snapshot, systems: snapshot.systems.map(system => ({...system, starClass: 'invalid'}))}), /класс звезды/);
assert.deepEqual(model(snapshot).countries, []);
const bases = model({...snapshot, systems: snapshot.systems.map(system => ({...system, baseOwnerId: '0', starbaseIds: ['14']}))});
assert.equal(bases.systems[0].baseOwnerId, '0');
assert.equal(bases.systems[0].ownerId, undefined);
assert.deepEqual(bases.systems[0].starbaseIds, ['14']);
const ownedSnapshot = {...snapshot, countries: [{id: '0', name: 'Empire'}], systems: snapshot.systems.map(system => ({...system, baseOwnerId: '0', starbaseIds: ['14']}))};
assert.equal(model(ownedSnapshot).countries[0].name, 'Empire');
assert.throws(() => model({...ownedSnapshot, countries: []}), /империя владельца/);
assert.throws(() => model({...ownedSnapshot, countries: [ownedSnapshot.countries[0], ownedSnapshot.countries[0]]}), /империя в снимке/);
const fullSnapshot = {...ownedSnapshot, countries: [{id: '0', name: 'Empire', type: 'default', flag: {category: 'human', file: '01.dds', colors: Array(6).fill('white')}}], fleets: [{id: '7', ownerId: '0', systemId: '0', nameKey: 'Fleet', shipIds: ['12', '13']}]};
const fullModel = model(fullSnapshot);
assert.equal(fullModel.liveCapabilities.borders, true);
assert.equal(fullModel.liveCapabilities.fleets, true);
assert.equal(fullModel.systems[0].ownerId, '0');
assert.equal(fullModel.markers[0].country.name, 'Empire');
assert.equal(fullModel.markers[0].system, fullModel.systems[0]);
assert.equal(fullModel.markers[0].fleet.shipIds.length, 2);
assert.equal(model({...fullSnapshot, fleets: [{...fullSnapshot.fleets[0], systemId: null}]}).markers.length, 0);
assert.equal(model({...fullSnapshot, fleets: [{...fullSnapshot.fleets[0], systemId: null}]}).liveFleetCount, 1);
assert.throws(() => model({...fullSnapshot, fleets: [{...fullSnapshot.fleets[0], ownerId: '99'}]}), /флот/);
assert.throws(() => model({...fullSnapshot, fleets: [{...fullSnapshot.fleets[0], systemId: '99'}]}), /система флота/);
assert.throws(() => model({...fullSnapshot, fleets: [...fullSnapshot.fleets, ...fullSnapshot.fleets]}), /флот/);
assert.throws(() => model({...fullSnapshot, countries: [{...fullSnapshot.countries[0], flag: {...fullSnapshot.countries[0].flag, file: '../bad.dds'}}]}), /флаг/);
assert.throws(() => model({...snapshot, systems: snapshot.systems.map(system => ({...system, baseOwnerId: '-1'}))}), /владелец/);
assert.equal(model(snapshot).sourceIdentity, model({...snapshot, systems: [...snapshot.systems].reverse()}).sourceIdentity);
assert.equal(model(snapshot).sourceIdentity, model(snapshot, key => `renamed-${key}`).sourceIdentity);
assert.notEqual(model(snapshot).sourceIdentity, model({...snapshot, processStartedAt: 'new-process'}).sourceIdentity);
assert.notEqual(model(snapshot).sourceIdentity, model({...snapshot, systems: snapshot.systems.map(system => ({...system, x: system.x + 1}))}).sourceIdentity);
assert.throws(() => model({...snapshot, systems: [snapshot.systems[0]]}), /неполный/);
assert.throws(() => model({...snapshot, systems: [snapshot.systems[0], snapshot.systems[0]]}), /Некорректные/);
assert.throws(() => model({...snapshot, schemaVersion: 2}), /Неподдерживаемый/);
console.log('PASS: live map adapter, no stale save layers, duplicate IDs and missing neighbors rejected');
